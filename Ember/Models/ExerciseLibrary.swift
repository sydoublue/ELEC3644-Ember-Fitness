import Foundation

/// Ember's built-in bodyweight library: five movement categories plus recovery items.
enum ExerciseLibrary {

    static let all: [Exercise] = push + squat + hinge + core + mobility + recovery

    static let byID: [String: Exercise] = Dictionary(uniqueKeysWithValues: all.map { ($0.id, $0) })

    static func exercise(_ id: String) -> Exercise? { byID[id] }

    static func regular(in category: MovementCategory) -> [Exercise] {
        all.filter { $0.category == category && !$0.isRecovery }
    }

    static func recovery(for area: BodyArea) -> Exercise? {
        recovery.first { $0.eases == area }
    }

